//! Generate `catalog_gen.rs` (FluidData entries + Variant enum) from curated JSONs.

use std::collections::HashMap;
use std::fs;
use std::path::Path;

use quote::{format_ident, quote};

use crate::BuildEnv;
use crate::fluids::{self, FluidFields};

pub(crate) fn generate_rust_catalog(env: &BuildEnv) {
    let entries = read_curated_fluids(&env.manifest_dir, &env.fluids);
    let tokens = render_catalog_tokens(&entries);
    write_catalog_file(&env.out_dir, tokens);
}

fn read_curated_fluids(manifest_dir: &Path, fluids: &[String]) -> Vec<(String, FluidFields)> {
    let dir = fluids::fluids_dir(manifest_dir);
    let mut entries: Vec<(String, FluidFields)> = Vec::with_capacity(fluids.len());
    let mut seen: HashMap<String, String> = HashMap::new();

    for file_stem in fluids {
        let fields = fluids::read_fluid(&dir, file_stem);
        let variant = to_variant(&fields.name);
        if let Some(prev) = seen.insert(variant.clone(), fields.name.clone()) {
            panic!(
                "variant identifier '{variant}' produced by both '{prev}' and '{}'. \
                 Adjust to_variant() or rename one of the fluids.",
                fields.name
            );
        }
        entries.push((variant, fields));
    }
    entries
}

/// CoolProp name → Rust identifier: drop parens, split on `-`, capitalize each
/// segment (`"n-Propane"` → `"NPropane"`, `"R1233zd(E)"` → `"R1233zdE"`).
fn to_variant(name: &str) -> String {
    let stripped: String = name.chars().filter(|c| c != &'(' && c != &')').collect();
    let mut out = String::new();
    for segment in stripped.split('-') {
        let mut chars = segment.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.extend(chars);
        }
    }
    out
}

fn render_catalog_tokens(entries: &[(String, FluidFields)]) -> proc_macro2::TokenStream {
    let fluid_inits = entries.iter().map(|(_, f)| {
        let (name, cas, formula) = (&f.name, &f.cas, &f.formula);
        let (molar_mass, t_critical, p_critical) = (f.molar_mass, f.t_critical, f.p_critical);
        let (t_min, t_max, p_max) = (f.t_min, f.t_max, f.p_max);
        quote! {
            FluidData {
                name: #name,
                cas: #cas,
                formula: #formula,
                molar_mass: #molar_mass,
                t_critical: #t_critical,
                p_critical: #p_critical,
                t_min: #t_min,
                t_max: #t_max,
                p_max: #p_max,
            }
        }
    });

    let variant_decls = entries.iter().enumerate().map(|(i, (v, _))| {
        let id = format_ident!("{}", v);
        let disc = i as u8;
        quote! { #id = #disc }
    });

    let all_variants = entries.iter().map(|(v, _)| {
        let id = format_ident!("{}", v);
        quote! { Variant::#id }
    });

    quote! {
        pub const FLUIDS: &[FluidData] = &[ #(#fluid_inits),* ];

        #[repr(u8)]
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
        pub enum Variant { #(#variant_decls),* }

        impl Variant {
            pub const ALL: &'static [Variant] = &[ #(#all_variants),* ];

            pub fn data(self) -> &'static FluidData {
                &FLUIDS[self as usize]
            }

            pub fn name(self) -> &'static str {
                self.data().name
            }
        }
    }
}

fn write_catalog_file(out_dir: &Path, tokens: proc_macro2::TokenStream) {
    let file = syn::parse2(tokens).expect("generated tokens are not a valid Rust file");
    let mut pretty = String::from(
        "// AUTO-GENERATED by coolprop-sys/build.rs. Do not edit by hand.\n\
         // Source: CoolProp/dev/fluids/*.json filtered by the curated list\n\
         // (COOLPROP_FLUIDS env override, else CURATED_FLUIDS).\n\n",
    );
    pretty.push_str(&prettyplease::unparse(&file));

    let dest = out_dir.join("catalog_gen.rs");
    fs::write(&dest, pretty).expect("failed to write catalog_gen.rs");
}
